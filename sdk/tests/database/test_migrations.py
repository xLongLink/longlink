import sys
import pytest
import sqlite3
from pathlib import Path
from sqlmodel import SQLModel
from contextlib import closing
from sqlalchemy import create_engine
from alembic.config import Config
from longlink.database import migrations as database_migrations


def test_make_migrations_creates_revisions_only_for_schema_operations(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    """Discover nested models once and create revisions only for schema changes."""

    # Arrange
    monkeypatch.chdir(tmp_path)
    monkeypatch.setenv("LONGLINK_ENV", "development")
    table_name = "autogenerated_inventory_items"
    module_name = "src.models.catalog.autogenerated_inventory"
    assert module_name not in sys.modules
    assert table_name not in SQLModel.metadata.tables

    # Match existing Solution metadata while leaving users for migration generation.
    engine = create_engine("sqlite:///dev.db")
    try:
        SQLModel.metadata.create_all(engine, tables=[table for table in SQLModel.metadata.sorted_tables if table.name != "users"])
    finally:
        engine.dispose()

    # Discover one new nested Solution model through the real migration loader.
    model_path = tmp_path / "src" / "models" / "catalog" / "autogenerated_inventory.py"
    model_path.parent.mkdir(parents=True)
    model_path.write_text(
        "from sqlmodel import Field, SQLModel\n"
        "\n\n"
        "class AutogeneratedInventoryItem(SQLModel, table=True):\n"
        '    """Inventory table generated by Alembic."""\n'
        "\n"
        f'    __tablename__ = "{table_name}"\n'
        "\n"
        "    id: int | None = Field(default=None, primary_key=True)\n",
        encoding="utf-8",
    )

    try:

        # Act
        migration_created = database_migrations.make_migrations()

        # Assert
        assert migration_created is True
        revisions = list((tmp_path / "migrations").glob("*.py"))
        assert len(revisions) == 1

        # Apply the generated revision and verify its table through an independent connection.
        database_migrations.apply_migrations()
        with closing(sqlite3.connect(tmp_path / "dev.db")) as connection:
            tables = connection.execute("SELECT name FROM sqlite_master WHERE type = 'table' AND name = ?", (table_name,)).fetchall()
            assert connection.execute("SELECT COUNT(*) FROM users").fetchone() == (0,)
        assert tables == [(table_name,)]

        # Suppress a second revision when the migrated schema already matches metadata.
        assert database_migrations.make_migrations() is False
        assert list((tmp_path / "migrations").glob("*.py")) == revisions
    finally:

        # Remove only this test's model metadata and module, including on migration failure.
        table = SQLModel.metadata.tables.get(table_name)
        if table is not None:
            SQLModel.metadata.remove(table)
        sys.modules.pop(module_name, None)


@pytest.mark.usefixtures("production_environment")
def test_production_migrations_rejects_missing_revisions_before_upgrade(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    """Fail production startup without committed Solution revisions."""

    # Arrange
    monkeypatch.chdir(tmp_path)
    monkeypatch.setattr(
        database_migrations.command, "upgrade", lambda *_: pytest.fail("Alembic upgrade must not run without Solution migrations")
    )

    # Act and assert
    with pytest.raises(RuntimeError, match="require migrations"):
        database_migrations.apply_migrations()


@pytest.mark.usefixtures("production_environment")
def test_production_migrations_upgrade_head_with_committed_revision(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    """Apply committed Solution revisions in production."""

    # Arrange
    migrations_path = tmp_path / "migrations"
    migrations_path.mkdir()
    migrations_path.joinpath("001_initial.py").write_text("", encoding="utf-8")
    captured: list[tuple[Config, str]] = []
    monkeypatch.chdir(tmp_path)

    def upgrade(config: Config, target: str) -> None:
        """Capture the Alembic configuration and revision target."""

        captured.append((config, target))

    monkeypatch.setattr(database_migrations.command, "upgrade", upgrade)

    # Act
    database_migrations.apply_migrations()

    # Assert
    [(config, target)] = captured
    assert target == "head"
    assert config.get_main_option("script_location") == str(database_migrations.CURRENT_FILE.parent)
    assert config.get_main_option("version_locations") == str(migrations_path)
