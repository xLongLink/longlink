import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { generateDtsBundle } from 'dts-bundle-generator';
import ts from 'typescript';
import iconImports from 'lucide-react/dynamicIconImports.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const target = new URL('../../sdk/longlink/.static/jsx/frontend.d.ts', import.meta.url);
const marker = '// Native component declarations generated by web/scripts/frontend.mjs.\n';
const printer = ts.createPrinter({ removeComments: true });
const original = await readFile(target, 'utf8');

if (!original.includes(marker)) throw new Error('Frontend declarations are missing the generated section marker.');

const [retained] = original.split(marker);
const [bundle] = generateDtsBundle(
    [
        {
            filePath: `${root}scripts/frontend.ts`,
            libraries: {
                inlinedLibraries: [
                    '@base-ui/react',
                    '@base-ui/utils',
                    '@tanstack/react-table',
                    '@tanstack/table-core',
                    '@tanstack/store',
                    '@tanstack/react-store',
                    '@dnd-kit/core',
                    '@dnd-kit/utilities',
                    '@dnd-kit/sortable',
                    '@dnd-kit/accessibility',
                    'react',
                    'react-hook-form',
                    'zod',
                    '@standard-schema/spec',
                    '@types/react',
                    'csstype',
                    'class-variance-authority',
                    '@floating-ui/react-dom',
                    '@floating-ui/dom',
                    '@floating-ui/core',
                    '@floating-ui/utils',
                    'clsx',
                    'shiki',
                    '@shikijs/types',
                    '@shikijs/vscode-textmate',
                    '@types/hast',
                    '@types/unist',
                    'recharts',
                    'victory-vendor',
                    '@types/d3-shape',
                    '@types/d3-path',
                    'react-day-picker',
                    'date-fns',
                ],
                allowedTypesLibraries: [],
            },
            output: { noBanner: true },
        },
    ],
    { preferredConfigPath: `${root}tsconfig.app.json` }
);
// Merging library modules into one namespace changes variance inference; infer it from the bundled structural types.
const normalized = ts.transform(ts.createSourceFile('native.d.ts', bundle, ts.ScriptTarget.Latest, true), [
    (context) => {
        const visit = (node) => {
            if (ts.isTypeParameterDeclaration(node)) {
                return ts.factory.updateTypeParameterDeclaration(
                    node,
                    node.modifiers?.filter((modifier) => modifier.kind !== ts.SyntaxKind.InKeyword && modifier.kind !== ts.SyntaxKind.OutKeyword),
                    node.name,
                    node.constraint,
                    node.default
                );
            }
            return ts.visitEachChild(node, visit, context);
        };
        return (node) => ts.visitNode(node, visit);
    },
]);
const generated = normalized.transformed[0];
const exports = new Set();
const typeExports = new Set();
const namespaceExports = new Set();
const namespaceNames = new Set(generated.statements.filter(ts.isModuleDeclaration).map((node) => node.name.text));
const typeNames = new Set(
    generated.statements
        .filter((node) => ts.isTypeAliasDeclaration(node) || ts.isInterfaceDeclaration(node))
        .map((node) => node.name.text)
);

// React's fallback DOM interfaces must not shadow the real DOM inside the generated namespace.
const globals = ts.createSourceFile(
    'global.d.ts',
    await readFile(`${root}node_modules/@types/react/global.d.ts`, 'utf8'),
    ts.ScriptTarget.Latest,
    true
);
const domNames = new Set(globals.statements.filter(ts.isInterfaceDeclaration).map((node) => node.name.text));
const dom = ts.createSourceFile(
    'lib.dom.d.ts',
    await readFile(new URL('./lib.dom.d.ts', import.meta.resolve('typescript')), 'utf8'),
    ts.ScriptTarget.Latest,
    true
);
const standardDomNames = new Set(dom.statements.filter((node) => node.name).map((node) => node.name.text));
const statements = generated.statements.filter((node) => {
    // IconName is published from the installed Lucide catalog below.
    if (
        ts.isImportDeclaration(node) &&
        ts.isStringLiteral(node.moduleSpecifier) &&
        node.moduleSpecifier.text === 'lucide-react/dynamic' &&
        !node.importClause?.name &&
        node.importClause?.namedBindings &&
        ts.isNamedImports(node.importClause.namedBindings) &&
        node.importClause.namedBindings.elements.every((specifier) => specifier.name.text === 'IconName' && !specifier.propertyName)
    )
        return false;

    if (ts.isImportDeclaration(node) || ts.isImportEqualsDeclaration(node)) {
        throw new Error(`Frontend declarations must not require external imports: ${node.getText(generated)}`);
    }
    if (
        ts.isInterfaceDeclaration(node) &&
        domNames.has(node.name.text) &&
        standardDomNames.has(node.name.text) &&
        node.members.length === 0
    )
        return false;
    if (ts.isExportDeclaration(node)) {
        if (node.moduleSpecifier) throw new Error('Frontend declarations must be self-contained.');
        if (node.exportClause && ts.isNamedExports(node.exportClause)) {
            for (const specifier of node.exportClause.elements) {
                exports.add(specifier.name.text);
                if (namespaceNames.has((specifier.propertyName ?? specifier.name).text)) {
                    namespaceExports.add(specifier.name.text);
                }
                if (typeNames.has((specifier.propertyName ?? specifier.name).text)) {
                    typeExports.add(specifier.name.text);
                }
            }
        }
        return Boolean(node.exportClause && ts.isNamedExports(node.exportClause) && node.exportClause.elements.length);
    }
    if (node.modifiers?.some((modifier) => modifier.kind === ts.SyntaxKind.ExportKeyword) && node.name) {
        exports.add(node.name.text);
        if (ts.isTypeAliasDeclaration(node) || ts.isInterfaceDeclaration(node)) typeExports.add(node.name.text);
    }
    if (
        ts.isVariableStatement(node) &&
        node.modifiers?.some((modifier) => modifier.kind === ts.SyntaxKind.ExportKeyword)
    ) {
        for (const declaration of node.declarationList.declarations) {
            if (ts.isIdentifier(declaration.name)) exports.add(declaration.name.text);
        }
    }
    return true;
});
const namespace = statements
    .map((node) =>
        printer
            .printNode(ts.EmitHint.Unspecified, node, generated)
            .replace(/^export declare /, 'export ')
            .replace(/^declare /, '')
    )
    .join('\n');
const names = [...exports].filter((name) => name !== 'FrontendElement').sort();
// Image and Text keep callable declarations above to avoid block-scoped collisions with lib.dom.
const aliases = names
    .filter((name) => name !== 'Image' && name !== 'Text')
    .map((name) =>
        namespaceExports.has(name) || typeExports.has(name)
            ? `import ${name} = NativeFrontend.${name};`
            : `declare const ${name}: typeof NativeFrontend.${name};`
    )
    .join('\n');
// Publish the installed Lucide catalog without bundling its component and React declarations.
const iconName = `type IconName = ${Object.keys(iconImports).map((name) => JSON.stringify(name)).join(' | ')};`;
const output = `${retained.trimEnd()}\n\n${marker}${iconName}\n\ndeclare namespace NativeFrontend {\n${namespace}\n}\n\n${aliases}\n`;

if (process.argv.includes('--check')) {
    if (output !== original) throw new Error('Frontend declarations are stale. Run bun run generate:frontend.');
} else {
    await writeFile(target, output);
}
