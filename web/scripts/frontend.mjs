import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { generateDtsBundle } from 'dts-bundle-generator';
import ts from 'typescript';

const root = fileURLToPath(new URL('../', import.meta.url));
const target = new URL('../../sdk/longlink/.static/jsx/frontend.d.ts', import.meta.url);
const marker = '// Native component declarations generated by web/scripts/frontend.mjs.\n';
const printer = ts.createPrinter({ removeComments: true });
const original = await readFile(target, 'utf8');

if (!original.includes(marker)) throw new Error('Frontend declarations are missing the generated section marker.');

const [retained] = original.split(marker);
const [bundle] = generateDtsBundle(
    [
        {
            filePath: `${root}scripts/frontend.ts`,
            libraries: {
                inlinedLibraries: [
                    '@base-ui/react',
                    '@base-ui/utils',
                    'react',
                    '@types/react',
                    'csstype',
                    'class-variance-authority',
                    '@floating-ui/react-dom',
                    '@floating-ui/dom',
                    '@floating-ui/core',
                    '@floating-ui/utils',
                    'clsx',
                    'shiki',
                    '@shikijs/types',
                    '@shikijs/vscode-textmate',
                    '@types/hast',
                    '@types/unist',
                ],
                allowedTypesLibraries: [],
            },
            output: { noBanner: true },
        },
    ],
    { preferredConfigPath: `${root}tsconfig.app.json` }
);
const generated = ts.createSourceFile('native.d.ts', bundle, ts.ScriptTarget.Latest, true);
const exports = new Set();

// React's fallback DOM interfaces must not shadow the real DOM inside the generated namespace.
const globals = ts.createSourceFile(
    'global.d.ts',
    await readFile(`${root}node_modules/@types/react/global.d.ts`, 'utf8'),
    ts.ScriptTarget.Latest,
    true
);
const domNames = new Set(globals.statements.filter(ts.isInterfaceDeclaration).map((node) => node.name.text));
const dom = ts.createSourceFile(
    'lib.dom.d.ts',
    await readFile(new URL('./lib.dom.d.ts', import.meta.resolve('typescript')), 'utf8'),
    ts.ScriptTarget.Latest,
    true
);
const standardDomNames = new Set(dom.statements.filter((node) => node.name).map((node) => node.name.text));
const statements = generated.statements.filter((node) => {
    if (ts.isImportDeclaration(node) || ts.isImportEqualsDeclaration(node)) {
        throw new Error(`Frontend declarations must not require external imports: ${node.getText(generated)}`);
    }
    if (
        ts.isInterfaceDeclaration(node) &&
        domNames.has(node.name.text) &&
        standardDomNames.has(node.name.text) &&
        node.members.length === 0
    )
        return false;
    if (ts.isExportDeclaration(node)) {
        if (node.moduleSpecifier) throw new Error('Frontend declarations must be self-contained.');
        if (node.exportClause && ts.isNamedExports(node.exportClause)) {
            for (const specifier of node.exportClause.elements) exports.add(specifier.name.text);
        }
        return Boolean(node.exportClause && ts.isNamedExports(node.exportClause) && node.exportClause.elements.length);
    }
    if (node.modifiers?.some((modifier) => modifier.kind === ts.SyntaxKind.ExportKeyword) && node.name) {
        exports.add(node.name.text);
    }
    if (
        ts.isVariableStatement(node) &&
        node.modifiers?.some((modifier) => modifier.kind === ts.SyntaxKind.ExportKeyword)
    ) {
        for (const declaration of node.declarationList.declarations) {
            if (ts.isIdentifier(declaration.name)) exports.add(declaration.name.text);
        }
    }
    return true;
});
const namespace = statements
    .map((node) =>
        printer
            .printNode(ts.EmitHint.Unspecified, node, generated)
            .replace(/^export declare /, 'export ')
            .replace(/^declare /, '')
    )
    .join('\n');
const names = [...exports].filter((name) => name !== 'FrontendElement').sort();
// Image keeps its callable declaration above to avoid a block-scoped collision with lib.dom.
const aliases = names
    .filter((name) => name !== 'Image')
    .map((name) => `declare const ${name}: typeof NativeFrontend.${name};`)
    .join('\n');
const output = `${retained.trimEnd()}\n\n${marker}declare namespace NativeFrontend {\n${namespace}\n}\n\n${aliases}\n`;

if (process.argv.includes('--check')) {
    if (output !== original) throw new Error('Frontend declarations are stale. Run bun run generate:frontend.');
} else {
    await writeFile(target, output);
}
